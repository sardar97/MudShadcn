#!/usr/bin/env node
// Generates src/MudShadcn/ShadcnThemeData.g.cs: shadcn/ui's colour themes (the base colours and
// accent themes of ui.shadcn.com/create) and the Tailwind grey scale behind each base colour.
//
//   node tools/generate-shadcn-themes.mjs [themes.ts] [theme.css]
//
// Both arguments are a file path or a URL and default to the sources on GitHub. Run it when shadcn
// adds or changes a theme; a new name also needs a member in ShadcnBaseColor or ShadcnColor
// (ShadcnThemeOptions.cs), which the build then asks for.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const THEMES_URL = "https://raw.githubusercontent.com/shadcn-ui/ui/main/apps/v4/registry/themes.ts";
const TAILWIND_URL = "https://raw.githubusercontent.com/tailwindlabs/tailwindcss/main/packages/tailwindcss/theme.css";

// shadcn's base colours (apps/v4/registry/base-colors.ts). Every other theme is an accent.
const BASE_COLORS = ["neutral", "stone", "zinc", "mauve", "olive", "mist", "taupe"];
// The steps MudShadcnTheme maps onto MudBlazor's palette (greys, contrast texts).
const SCALE_STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const read = async (source) =>
    /^https?:/.test(source) ? await (await fetch(source)).text() : await readFile(source, "utf8");

const themesSource = await read(process.argv[2] ?? THEMES_URL);
const tailwindSource = await read(process.argv[3] ?? TAILWIND_URL);

// themes.ts is one array literal of plain objects. Turn it into JSON instead of evaluating it.
function parseThemes(literal) {
    // The array closes on a line of its own; what follows ("as const satisfies RegistryItem[]") is types.
    const json = literal
        .slice(0, literal.lastIndexOf("\n]") + 2)
        .replace(/\/\/.*$/gm, "")
        .replace(/([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:/g, '$1"$2":')
        .replace(/,(\s*[}\]])/g, "$1");
    return JSON.parse(json);
}

// "THEMES: RegistryItem[] = [" has a "[" of its own before the array starts.
const arrayStart = themesSource.indexOf("= [");
if (arrayStart < 0) {
    throw new Error("themes.ts: could not find the THEMES array");
}
const themes = parseThemes(themesSource.slice(arrayStart + 2));

const pascal = (name) => name.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());
const bases = BASE_COLORS.map((name) => {
    const theme = themes.find((t) => t.name === name);
    if (!theme) {
        throw new Error(`themes.ts has no base colour "${name}"`);
    }
    return theme;
});
const accents = themes.filter((t) => !BASE_COLORS.includes(t.name));

// --color-neutral-50: oklch(98.5% 0 none);
const scales = {};
for (const [, name, step, value] of tailwindSource.matchAll(/--color-([a-z]+)-(\d+):\s*(oklch\([^)]*\))/g)) {
    (scales[name] ??= {})[step] = value;
}
for (const name of BASE_COLORS) {
    for (const step of SCALE_STEPS) {
        if (!scales[name]?.[step]) {
            throw new Error(`Tailwind's theme.css has no --color-${name}-${step}`);
        }
    }
}

const entries = (vars, indent) =>
    Object.entries(vars)
        .filter(([key]) => key !== "radius")
        .map(([key, value]) => `${indent}["${key}"] = "${value}",`)
        .join("\n");

const dictionaryCases = (items, enumName) =>
    items
        .flatMap((theme) =>
            ["light", "dark"].map(
                (mode) =>
                    `        (${enumName}.${pascal(theme.name)}, ${mode === "dark"}) => new()\n        {\n${entries(theme.cssVars[mode], "            ")}\n        },`
            )
        )
        .join("\n");

const scaleCases = BASE_COLORS.flatMap((name) =>
    SCALE_STEPS.map((step) => `        (ShadcnBaseColor.${pascal(name)}, ${step}) => "${scales[name][step]}",`)
).join("\n");

const output = `// <auto-generated>
//   Generated by tools/generate-shadcn-themes.mjs from shadcn/ui's apps/v4/registry/themes.ts and
//   Tailwind's theme.css. Do not edit: change the script, or re-run it for new upstream values.
// </auto-generated>

namespace MudShadcn;

internal static class ShadcnThemeData
{
    /// <summary>The tokens of a base colour, as shadcn's <c>:root</c> (light) or <c>.dark</c> block.</summary>
    internal static Dictionary<string, string> Base(ShadcnBaseColor color, bool dark) => (color, dark) switch
    {
${dictionaryCases(bases, "ShadcnBaseColor")}
        _ => throw new ArgumentOutOfRangeException(nameof(color), color, null),
    };

    /// <summary>The tokens an accent theme overrides on top of a base colour.</summary>
    internal static Dictionary<string, string> Accent(ShadcnColor color, bool dark) => (color, dark) switch
    {
${dictionaryCases(accents, "ShadcnColor")}
        _ => throw new ArgumentOutOfRangeException(nameof(color), color, null),
    };

    /// <summary>A step of the Tailwind grey scale a base colour is taken from.</summary>
    internal static string Scale(ShadcnBaseColor color, int step) => (color, step) switch
    {
${scaleCases}
        _ => throw new ArgumentOutOfRangeException(nameof(step), step, null),
    };
}
`;

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "MudShadcn", "ShadcnThemeData.g.cs");
await writeFile(target, output);
console.log(`${bases.length} base colours, ${accents.length} accent themes -> ${target}`);
console.log(`base colours: ${bases.map((t) => pascal(t.name)).join(", ")}`);
console.log(`accents:      ${accents.map((t) => pascal(t.name)).join(", ")}`);
